<?php
declare(strict_types=1);

namespace AgeCMS;

/**
 * Site configuration and secrets, stored in data/config.php (mode 0600).
 * Secrets live here and not in the database, so a database backup or an agent
 * reading settings never exposes them.
 */
final class Config
{
    private const DEFAULTS = [
        'site_url' => '',
        'secret' => '',
        'indexnow_key' => '',
        'indexnow' => true,
        'trusted_proxies' => [],
        'trusted_publishers' => [],
        'secrets' => [],
        'circuit_breaker' => ['ratio' => 0.15, 'min_touched' => 3, 'max_creates' => 500],
        'backup' => ['keep' => 7, 'telegram' => false, 'before_agent' => true, 'keep_auto' => 5],
        'agent_access' => ['self_issue' => true, 'token_days' => 90, 'invite_hours' => 24],
        'mail' => ['transport' => 'mail', 'from' => '', 'from_name' => '', 'leads_to' => '', 'leads_notify' => true, 'smtp' => ['host' => '', 'port' => 465, 'secure' => 'ssl', 'user' => '', 'pass' => '']],
        'rate_limit' => ['mcp_per_minute' => 120, 'login_fails' => 5, 'login_window' => 900],
    ];

    /** @var array<string,mixed>|null */
    private static ?array $data = null;

    /** @return array<string,mixed> */
    public static function all(): array
    {
        if (self::$data === null) {
            $file = self::file();
            $loaded = is_file($file) ? (static fn() => require $file)() : [];
            self::$data = array_replace_recursive(self::DEFAULTS, is_array($loaded) ? $loaded : []);
        }
        return self::$data;
    }

    public static function get(string $path, mixed $default = null): mixed
    {
        $node = self::all();
        foreach (explode('.', $path) as $part) {
            if (!is_array($node) || !array_key_exists($part, $node)) {
                return $default;
            }
            $node = $node[$part];
        }
        return $node;
    }

    /** @param array<string,mixed> $data */
    public static function save(array $data): void
    {
        $file = self::file();
        $dir = dirname($file);
        if (!is_dir($dir) && !mkdir($dir, 0700, true) && !is_dir($dir)) {
            throw new AgeCMSException("Cannot create {$dir}");
        }
        $tmp = $file . '.tmp' . bin2hex(random_bytes(4));
        $php = "<?php\n// Generated by AgeCMS. Contains secrets, do not publish.\nreturn " . var_export($data, true) . ";\n";
        if (file_put_contents($tmp, $php, LOCK_EX) === false) {
            throw new AgeCMSException("Cannot write {$tmp}");
        }
        chmod($tmp, 0600);
        rename($tmp, $file);
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($file, true);
        }
        self::$data = null;
    }

    /** Sets one dotted key and writes the file. */
    public static function set(string $path, mixed $value): void
    {
        $file = self::file();
        $current = is_file($file) ? (static fn() => require $file)() : [];
        $node = &$current;
        foreach (explode('.', $path) as $part) {
            if (!isset($node[$part]) || !is_array($node[$part])) {
                $node[$part] = [];
            }
            $node = &$node[$part];
        }
        $node = $value;
        unset($node);
        self::save($current);
    }

    public static function file(): string
    {
        return AGECMS_DATA . '/config.php';
    }

    public static function reset(): void
    {
        self::$data = null;
    }
}
